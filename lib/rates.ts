export function defaultCategories(): Category[] {
  return Object.entries(DEFAULT_CATEGORIES).map(([name, codes]) => ({
    name,
    codes: { ...codes },
  }));
}

export function buildRateIndex(categories: Category[]): Record<string, number[]> {
  const rates: Record<string, number[]> = {};
  for (const cat of categories) {
    for (const [code, catRates] of Object.entries(cat.codes)) {
      rates[code] = catRates;
    }
  }
  return rates;
}

export function categoryOfCode(categories: Category[], code: string): string | null {
  const cat = categories.find((c) => Object.prototype.hasOwnProperty.call(c.codes, code));
  return cat ? cat.name : null;
}

export function normalizeCode(raw: string): string {
  return raw.trim().toUpperCase().replace(/\s+/g, '').replace(/["“”]/g, '');
}

export function lookupRates(rates: Record<string, number[]>, raw: string): number[] | null {
  const norm = normalizeCode(raw);
  return Object.prototype.hasOwnProperty.call(rates, norm) ? rates[norm] : null;
}
